class FakeWeb:
    """
    searches answer from `searches` (query -> [video ids], or a response, or a list given in
    turn); videos from `videos` (id -> video()); channels from `channels` (ids that exist);
    wikidata from `wikidata` ((property, id) -> [channel ids]); musicbrainz from
    `musicbrainz` (spotify id -> [youtube urls]). anything else finds nothing
    """

    def __init__(self, searches=None, videos=None, channels=(), wikidata=None, musicbrainz=None, musicbrainz_503s=0, forbidden=False):
        self.searches = dict(searches or {})
        self.videos = dict(videos or {})
        self.channels = set(channels)
        self.wikidata = dict(wikidata or {})
        self.musicbrainz = dict(musicbrainz or {})
        # musicbrainz answers this many requests with 503 first, as it does when busy
        self.musicbrainz_503s = musicbrainz_503s
        # youtube refuses the key, as it does a referrer-restricted one from a server
        self.forbidden = forbidden
        self.requests = []
        self.sleeps = []
        self.now = 1_800_000_000.0

    def record(self, method, url, params=None, data=None, headers=None):
        self.requests.append(SimpleNamespace(method=method, url=url, params=params or {}, data=data, headers=headers or {}))

    def get(self, url, params=None, headers=None, timeout=None):
        self.record("GET", url, params=params, headers=headers)
        if "musicbrainz.org" in url:
            return self.musicbrainz_answer(url, params)
        if self.forbidden:
            return response(403, {"error": {"code": 403, "errors": [{"reason": "forbidden"}], "status": "PERMISSION_DENIED"}})
        path = url.rsplit("/", 1)[1]
        if path == "search":
            answer = self.searches.get(params["q"], [])
            if isinstance(answer, list) and answer and not isinstance(answer[0], str):
                answer = answer.pop(0)
            if hasattr(answer, "status_code"):
                return answer
            return response(200, {"items": [{"id": {"kind": "youtube#video", "videoId": v}} for v in answer]})
        ids = params["id"].split(",")
        if path == "videos":
            answer = self.videos.get("__response__")
            if isinstance(answer, list):
                return answer.pop(0)
            return response(200, {"items": [self.videos[i] for i in ids if i in self.videos]})
        if path == "channels":
            return response(200, {"items": [{"id": i} for i in ids if i in self.channels]})
        return response(404, {"error": {"errors": [{"reason": "notFound"}]}})

    def post(self, url, data=None, headers=None, timeout=None):
        self.record("POST", url, data=data, headers=headers)
        query = data["query"]
        prop = "P1902" if "wdt:P1902" in query else "P2850"
        ids = query.split("VALUES ?id {")[1].split("}")[0].replace('"', "").split()
        bindings = [
            {"id": {"value": i}, "yt": {"value": channel}}
            for i in ids
            for channel in self.wikidata.get((prop, i), [])
        ]
        return response(200, {"results": {"bindings": bindings}})

    def musicbrainz_answer(self, url, params):
        if self.musicbrainz_503s:
            self.musicbrainz_503s -= 1
            return response(503, {"error": "busy"})
        if url.endswith("/url"):
            spotify_id = params["resource"].rsplit("/", 1)[1]
            if spotify_id not in self.musicbrainz:
                return response(404, {"error": "Not Found"})
            return response(200, {"relations": [{"type": "free streaming", "artist": {"id": f"mbid-{spotify_id}"}}]})
        spotify_id = url.rsplit("/", 1)[1].removeprefix("mbid-")
        return response(200, {"relations": [{"type": "youtube", "url": {"resource": u}} for u in self.musicbrainz.get(spotify_id, [])]})

    @property
    def search_queries(self):
        return [r.params["q"] for r in self.requests if r.url.endswith("/search")]

    @property
    def youtube_requests(self):
        return [r for r in self.requests if "googleapis.com" in r.url]

    def clock(self):
        return self.now

    def sleep(self, seconds):
        self.sleeps.append(seconds)
        self.now += seconds

    def youtube(self, key=TEST_KEY):
        return YouTubeClient(key, session=self, sleep=self.sleep)

    def music_ids(self):
        return MusicIds(session=self, sleep=self.sleep, clock=self.clock)

    def patch(self, where="core.management.commands.match_youtube_artists"):
        """use this fake wherever `where` makes its clients"""
        return mock.patch.multiple(
            where, YouTubeClient=lambda key: self.youtube(key), MusicIds=lambda: self.music_ids()
        )
